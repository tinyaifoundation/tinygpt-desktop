const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
const { _electron } = require(process.env.TINYGPT_PLAYWRIGHT_PACKAGE || require.resolve('playwright', { paths: [path.resolve(__dirname, '../../desktop-clone')] }));
const root = path.resolve(__dirname,'../..');
const output = path.join(root,'artifacts/tool-icon-audit');
const testFile = path.join(output,'test-recorded-changes.json');
const env = { ...process.env, TOOL_ICON_AUDIT_TEST:'1' };
delete env.ELECTRON_RUN_AS_NODE;
let app;
async function launch() {
  app = await _electron.launch({ executablePath:path.join(root,'desktop-clone/node_modules/electron/dist/electron.exe'), args:[__dirname], env, timeout:30000 });
  const page = await app.firstWindow();
  page.setDefaultTimeout(10000);
  await page.locator('#app').waitFor({state:'visible',timeout:45000});
  return page;
}
(async()=>{
  await fs.rm(testFile,{force:true});
  let page = await launch();
  const errors = [];
  page.on('pageerror',error=>errors.push(error.message));
  const sourceAudit = JSON.parse(await fs.readFile(path.join(output,'audit.json'),'utf8'));
  assert.equal(await page.locator('.tool-card').count(),sourceAudit.rows.length);
  const byId = Object.fromEntries(sourceAudit.rows.map(row => [row.id,row]));
  for (const name of ['calculate','search_help','read_observation','read_source','list_files','read_file','search_files','write_file','edit_file','run_command','load_tools','browser_tabs','browser_preview','computer_screenshot','computer_activate_window','code_delegate','code_devtools','work_ask_user','work_history','model_load','file_prepare']) assert.ok(byId[name], name + ' is discovered');
  const overrides=JSON.parse(await fs.readFile(path.join(root,'desktop-clone/src/shared/tool-icon-overrides.json'),'utf8'));
  for (const row of sourceAudit.rows.filter(row=>row.name.startsWith('browser_') || row.name === 'code_devtools')) assert.equal(row.slug,overrides[row.id] || 'globe',row.id);
  assert.equal(byId.calculate.slug,'calculator');
  assert.equal(byId.computer_screenshot.slug,'camera');
  assert.equal(byId.work_ask_user.slug,'question-circle');
  assert.equal(byId['activity/context_optimization'].slug,'revote');
  assert.equal(byId['activity/context_optimization'].complete,'Optimized the conversation');
  assert.equal(byId['gmail/search_mail'].group,'Gmail');
  assert.equal(byId['google-calendar/list_events'].group,'Google Calendar');
  await page.locator('#search').fill('computer_');
  assert.equal(await page.locator('.tool-card').count(),sourceAudit.rows.filter(row=>row.name.startsWith('computer_')).length);
  await page.locator('#search').fill('');
  await page.locator('[data-tool-id="search_web"]').click();
  await page.locator('#slug').fill('solar:star-linear');
  await page.locator('#save-replacement').click();
  await page.waitForFunction(()=>document.querySelector('#save-status').textContent.includes('1 replacement'));
  let state = JSON.parse(await fs.readFile(testFile,'utf8'));
  assert.equal(state.replacements[0].tool,'search_web');
  assert.equal(state.replacements[0].solarSlug,'star');
  await page.locator('#slug').fill('solar:file-linear');
  await page.locator('#refresh-audit').click();
  await page.waitForFunction(()=>!document.querySelector('#refresh-audit').disabled,{},{timeout:45000});
  assert.equal(await page.locator('#slug').inputValue(),'solar:file-linear','Refresh preserves the current draft');
  const afterRefresh=JSON.parse(await fs.readFile(testFile,'utf8'));
  assert.deepEqual(afterRefresh,state,'Refresh never rewrites saved choices');
  await page.getByRole('button',{name:/^New tools/}).click();
  assert.equal(await page.locator('.tool-card').count(),sourceAudit.newToolIds.length);
  await page.getByRole('button',{name:/^All tools/}).click();
  await page.locator('#slug').fill('not-a-real-icon');
  assert.equal(await page.locator('#save-replacement').isDisabled(),true);
  const invalidRejected = await page.evaluate(async()=>{try{await window.auditApp.record({tool:'search_web',solarSlug:'not-a-real-icon'});return false;}catch{return true;}});
  assert.equal(invalidRejected,true);
  await page.locator('#copy-request').click();
  const copied = await app.evaluate(({clipboard})=>clipboard.readText());
  assert.match(copied,/search_web/); assert.match(copied,/test-recorded-changes.json/);
  await app.close(); app=null;
  page = await launch();
  assert.match(await page.locator('#save-status').innerText(),/1 replacement/);
  assert.equal(await page.locator('#slug').inputValue(),'star');
  await page.locator('[data-mode="active"]').click();
  assert.match(await page.locator('#candidate-chain').innerText(),/Searching the web/);
  await page.locator('#slug').fill('file');
  const iconCount = await page.locator('.icon-option').count(); assert.ok(iconCount>1);
  await page.locator('.icon-option[aria-label="file"]').click();
  assert.equal(await page.locator('#slug').inputValue(),'file');
  await page.locator('[data-mode="complete"]').click();
  await page.locator('#slug').fill('star');
  await page.screenshot({path:path.join(output,'desktop-app.png')});
  await page.setViewportSize({width:960,height:720});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.emulateMedia({colorScheme:'dark'});
  await page.screenshot({path:path.join(output,'desktop-app-dark.png')});
  await page.locator('.undo-button').click();
  await page.waitForFunction(()=>document.querySelector('#save-status').textContent==='No changes recorded');
  state=JSON.parse(await fs.readFile(testFile,'utf8')); assert.equal(state.replacements.length,0);
  assert.deepEqual(errors,[]);
  await app.close(); app=null;
  await fs.rm(testFile,{force:true});
  console.log(`PASS: ${sourceAudit.rows.length} current entries, production icon rules, new tools, correct connector groups, refresh preserving drafts and saved mappings, search, slug validation, disk saves, restart persistence, clipboard, icon browser, labels, removal, narrow/dark layouts.`);
})().catch(async error=>{console.error(error);if(app)await app.close();process.exitCode=1;});
