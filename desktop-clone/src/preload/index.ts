import type { ChatUpdate } from '../shared/chat';
import { ChatUpdateDecoder, ChatUpdateEncoder, type ChatPacket } from '../core/chat-updates';

const chatDecoder = new ChatUpdateDecoder();
const legacyEncoder = new ChatUpdateEncoder();
const chatListeners = new Set<(update: ChatUpdate) => void>();
const packetListeners = new Set<(packets: ChatPacket[]) => void>();
// Decode once per window, not once per subscriber (which would append twice).
ipcRenderer.on('tinygpt:chat-update', (_event, packets: ChatPacket[] | ChatUpdate) => {
  const batch = Array.isArray(packets) ? packets : [legacyEncoder.encode(packets)];
  for (const listener of packetListeners) listener(batch);
  for (const packet of batch) {
    const update = chatDecoder.decode(packet);
    for (const listener of chatListeners) listener(update);
  }
});

