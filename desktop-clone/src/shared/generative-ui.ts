/** Convert historic Assistant UI trees at read time; saved records stay intact. */
export function restoreSavedChatUI(value: unknown): { ui: Spec; partial: boolean } {
  if (value && typeof value === 'object' && 'root' in value) return { ui: validateChatUI(value), partial: false };
  const restored = restoreLegacy(value);
  const elements: Spec['elements'] = {};
  let next = 0;
  function convert(value: unknown): string {
    const id = `legacy-${next++}`;
    if (Array.isArray(value)) { elements[id] = { type: 'Stack', props: {}, children: value.map(convert) }; return id; }
    if (!value || typeof value !== 'object') { elements[id] = { type: 'Text', props: { value: String(value ?? '') }, children: [] }; return id; }
    const { $type, $key, children, ...original } = value as Record<string, unknown>;
    let type = String($type); let props: Record<string, unknown> = original;
    switch (type) {
      case 'Col': case 'Row': case 'ListView': case 'ListViewItem': type = 'Stack'; props = { direction: $type === 'Row' ? 'horizontal' : 'vertical' }; break;
      case 'Header': type = 'Heading'; props = { text: original.text }; break;
      case 'Text': case 'Caption': case 'Markdown': case 'Badge': type = 'Text'; props = { value: original.value }; break;
      case 'Card': props = { ...(original.title ? { title: original.title } : {}) }; break;
      case 'Fact': type = 'MetricGrid'; props = { metrics: [original] }; break;
      case 'Chart': type = 'ChartPanel'; props = { title: 'Chart', ...original }; break;
      case 'FollowUp': type = 'FollowUpGroup'; props = { suggestions: [original] }; break;
      case 'Spacer': case 'Divider': type = 'Stack'; props = {}; break;
    }
    elements[id] = { type, props, children: children === undefined ? [] : (Array.isArray(children) ? children : [children]).map(convert) };
    if (elements[id].children!.length && !['Card', 'Stack'].includes(type)) {
      const leaf = `legacy-${next++}`; elements[leaf] = { type, props, children: [] };
      elements[id] = { type: 'Stack', props: {}, children: [leaf, ...elements[id].children!] };
    }
    return id;
  }
  const root = convert(restored.ui);
  return { ui: validateChatUI({ root, elements }), partial: restored.partial };
}
