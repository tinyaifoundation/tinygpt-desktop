import { validateSpec, type Spec } from '@json-render/core';
import { z } from 'zod';
import { chatUICatalog, chatUIComponents } from './chat-ui-catalog';
import { restoreSavedChatUI as restoreLegacy } from './legacy-generative-ui';
export { chatUICatalog, chatUIComponents } from './chat-ui-catalog';

export type ChatUINode = Record<string, unknown>;
export const CHAT_UI_MAX_CHARACTERS = 80000;
const elementSchema = z.object({ type: z.string(), props: z.record(z.string(), z.unknown()), children: z.array(z.string().min(1).max(100)).max(150).default([]) }).strict();
const specSchema = z.object({ root: z.string().min(1).max(100), elements: z.record(z.string().min(1).max(100), elementSchema) }).strict();

export function validateChatUI(value: unknown): Spec & ChatUINode {
  if ((JSON.stringify(value)?.length ?? Infinity) > CHAT_UI_MAX_CHARACTERS) throw new Error('The interface is too large.');
  const parsed = specSchema.parse(value);
  const keys = Object.keys(parsed.elements);
  if (!keys.length || keys.length > 150) throw new Error('Use 1–150 interface elements.');
  // Props are inert catalog data. State, expressions, events and directives
  // are deliberately outside this chat output contract.
  for (const [key, element] of Object.entries(parsed.elements)) {
    if (['__proto__', 'constructor', 'prototype'].includes(key)) throw new Error('Invalid element ID.');
    if (!Object.hasOwn(chatUIComponents, element.type)) throw new Error(`elements.${key}: Select a catalog component.`);
    const definition = chatUIComponents[element.type as keyof typeof chatUIComponents];
    const result = definition.props.safeParse(element.props);
    if (!result.success) throw new Error(`elements.${key}.props (${element.type}): ${result.error.issues.slice(0, 3).map(issue => `${issue.path.join('.')}: ${issue.message}`).join('; ')}`);
    element.props = result.data;
    if (!definition.slots.length && element.children.length) throw new Error(`elements.${key}: ${element.type} does not accept children.`);
    if (element.type === 'Comparison' || element.type === 'Table') {
      const { columns, rows } = element.props as { columns: { format?: { kind: string; currency?: string } }[]; rows: unknown[][] };
      if (rows.some(row => row.length !== columns.length)) throw new Error(`elements.${key}.rows: Every row must have exactly ${columns.length} cells.`);
      if (columns.some(column => column.format?.kind === 'currency' && !column.format.currency)) throw new Error(`elements.${key}.columns: Currency formatting requires a currency code such as USD.`);
    }
    if (element.type === 'ChartPanel') {
      const props = element.props as { variant: string; data?: { label?: string; value: number }[]; series?: { label?: string; data: { label?: string; value: number }[] }[] };
      const groups = props.series ?? [{ data: props.data }];
      const minimum = props.variant === 'bar' ? 1 : 2;
      if (!groups.length || groups.some(group => !group.data || group.data.length < minimum)) throw new Error(`elements.${key}: Provide ${minimum}–60 points per series.`);
      if (groups.some(group => group.data!.length !== groups[0].data!.length)) throw new Error(`elements.${key}: All series must have the same number of points.`);
      if (props.series && props.series.length > 1 && props.series.some(group => !group.label?.trim())) throw new Error(`elements.${key}: Name every series.`);
      if (props.variant !== 'sparkline' && groups.some(group => group.data!.some(point => !point.label?.trim()))) throw new Error(`elements.${key}: Label every point.`);
      if (groups.some(group => group.data!.some((point, index) => point.label !== groups[0].data![index].label))) throw new Error(`elements.${key}: Match point labels across series.`);
    }
  }
  const structural = validateSpec(parsed, { checkOrphans: true });
  if (!structural.valid) throw new Error(structural.issues.map(issue => issue.message).join('; '));
  const reached = new Set<string>(); const ancestors = new Set<string>();
  function visit(key: string, depth: number) {
    if (ancestors.has(key)) throw new Error('The interface contains a cycle.');
    if (depth > 12) throw new Error('The interface exceeds the nesting limit.');
    if (reached.has(key)) throw new Error('Each element must have one parent; use a separate element ID for repeated content.');
    reached.add(key); ancestors.add(key);
    parsed.elements[key].children.forEach(child => visit(child, depth + 1));
    ancestors.delete(key);
  }
  visit(parsed.root, 0);
  if (reached.size !== keys.length) throw new Error('Remove elements that are not reachable from root.');
  const result = chatUICatalog.validate(parsed);
  if (!result.success) throw new Error('The interface does not match the component catalog.');
  return parsed as Spec & ChatUINode;
}

// The provider receives per-component prop schemas generated by json-render.
// Exclude directives unsupported by our host, reducing repeated schema framing.
function providerParameters() {
  const generated = chatUICatalog.jsonSchema() as Record<string, any>;
  function restrict(value: any): void {
    if (!value || typeof value !== 'object') return;
    if (value.properties?.type && value.properties?.props && value.properties?.children) {
      const name = value.properties.type.const;
      if (name && Object.hasOwn(chatUIComponents, name)) value.description = chatUIComponents[name as keyof typeof chatUIComponents].description;
      delete value.properties.slots; delete value.properties.visible; delete value.properties.repeat;
    }
    Object.values(value).forEach(restrict);
  }
  restrict(generated);
  generated.properties.root.description = 'ID of the root element. Each child is an ID in elements.';
  return generated;
}
export const presentParameters = providerParameters();
export const compactPresentParameters = presentParameters;
export const presentArguments = z.record(z.string(), z.unknown()).transform((value, context) => {
  try { return validateChatUI(value); }
  catch (error) { context.addIssue({ code: 'custom', message: error instanceof Error ? error.message : 'Invalid interface.' }); return z.NEVER; }
});

