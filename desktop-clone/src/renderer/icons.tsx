// Keep semantic UI names while importing only the Solar Linear glyphs we use.
// Leave size unset: Solar's size prop writes inline dimensions over our CSS sizes.
function appIcon(Component: Icon, mirrored = false, rotation = 0): Icon {
  return forwardRef<SVGSVGElement, IconProps>(({ className, style, ...props }, ref) =>
    <Component ref={ref} aria-hidden={props['aria-label'] || props.alt ? undefined : true} {...props} className={className} style={{ ...((mirrored || rotation) ? { transform: `${mirrored ? 'scaleX(-1)' : ''} ${rotation ? `rotate(${rotation}deg)` : ''}`.trim() } : {}), ...style }} />);
}
